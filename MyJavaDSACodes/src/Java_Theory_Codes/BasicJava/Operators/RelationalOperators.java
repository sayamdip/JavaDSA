package Java_Theory_Codes.BasicJava.Operators;

public class RelationalOperators {
    public static void main(String[] args){
        int num1=50;
        int num2=80;

        //1) Equal To (==) Operator
        System.out.println("Equal To Operator= "+(num1==num2));

        //2) Not Equal To (!=) Operator
        System.out.println("Not Equal To Operator= "+(num1!=num2));

        //3) Greater Than (>) Operator
        System.out.println("Greater Than Operator= "+(num1>num2));

        //4) Less Than (<) Operator
        System.out.println("Less Than Operator= "+(num1<num2));

        //5) Greater Than Or Equal To (>=) Operator
        System.out.println("Greater Than Or Equal To Operator= "+(num1>=num2));

        //6) Less Than Or Equal To (<=) Operator
        System.out.println("Less Than Or Equal To Operator= "+(num1<=num2));
    }
}
