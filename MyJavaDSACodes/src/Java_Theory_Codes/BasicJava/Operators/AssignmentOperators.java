package Java_Theory_Codes.BasicJava.Operators;

public class AssignmentOperators {
    public static void main(String[] args){
        //Assignment Operators
        //1) Simple Assignment Operator (=)
        int a=40;
        System.out.println("Simple Assignment Operator= "+a);

        //2) Addition Assignment Operator (+=)
        a+=40;
        System.out.println("Addition Assignment Operator= "+a);

        //3) Subtraction Assignment Operator (-=)
        a-=20;
        System.out.println("Subtraction Assignment Operator= "+a);

        //4) Multiplication Assignment Operator
        a*=20;
        System.out.println("Multiplication Assignment Operator= "+a);

        //5) Division Assignment Operator
        a/=20;
        System.out.println("Division Assignment Operator= "+a);

        //6) Modulus Assignment Operator
        a%=30;
        System.out.println("Modulus Assignment Operator= "+a);
    }
}
