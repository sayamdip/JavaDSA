package Java_Theory_Codes.BasicJava;

public class DataTypes {
    public static void main(String[] args){
        // Primitive Data Types

        //1) Boolean
        boolean a=true;
        boolean b= false;

        //2) Byte
        byte age=10;
        byte temp1=-10;

        //3) Short
        short students=1000;
        short temp2=-40;

        //4) Integer
        int population=20000000;
        int distance=15000000;

        //5) Long
        long Worldpopulation=70000000000000L;
        long lightyears=9460730472580800L;

        //6) Float
        float pi=3.14f;
        float gravity=9.81f;

        //7) Double
        double pi2=3.141592653589793;
        double avogadro = 6.02214076e23;

        //8) Char
        char character='S';
        char character2='o';


        //Non-Primitive Data Type

        //1) String
        String str="Sayamdip";
        String str2="Dey Chaklader";

        //2) Array
        int[] num={1,2,3,4,5};
        String[] str3={"Sayamdip","Rick","Dey","Chaklader"};

        //3) Class

        //4) Object

        //5) Interface

        System.out.println("Boolean Data Type");
        System.out.println(a);
        System.out.println(b);
        System.out.println("Byte Data Type");
        System.out.println(age);
        System.out.println(temp1);
        System.out.println("Short Data Type");
        System.out.println(students);
        System.out.println(temp2);
        System.out.println("Integer Data Type");
        System.out.println(population);
        System.out.println(distance);
        System.out.println("Long Data Type");
        System.out.println(Worldpopulation);
        System.out.println(lightyears);
        System.out.println("Float Data Type");
        System.out.println(pi);
        System.out.println(gravity);
        System.out.println("Double Data Type");
        System.out.println(pi2);
        System.out.println(avogadro);
        System.out.println("Char Data Type");
        System.out.println(character);
        System.out.println(character2);
        System.out.println("String Data Type");
        System.out.println(str);
        System.out.println(str2);
        System.out.println("Array Data Type");
        System.out.println(num[0]);
        System.out.println(str3[3]);
    }
}
