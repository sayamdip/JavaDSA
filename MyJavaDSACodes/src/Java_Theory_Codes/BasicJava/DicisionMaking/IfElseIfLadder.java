package Java_Theory_Codes.BasicJava.DicisionMaking;

public class IfElseIfLadder {
    public static void main(String[] args){
        int a=40;
        if(a==30){
            System.out.println(a+" Is 30.");
        }
        else if(a==40){
            System.out.println(a+" Is 40.");
        }
        else if(a==50){
            System.out.println(a+" Is 50.");
        }
        else{
            System.out.println(a+" Is Greater Than 50.");
        }

    }
}
